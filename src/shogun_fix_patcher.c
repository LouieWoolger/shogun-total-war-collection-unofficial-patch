static bool bytes_at_match_hex(const wchar_t *path, DWORD offset, const char *hex, bool *matches)
{
    unsigned char *expected = NULL;
    size_t len = hex_to_bytes(hex, &expected);
    if (!expected) {
        fprintf(stderr, "error=invalid_previous_manifest offset=0x%08lX\n", (unsigned long)offset);
        return false;
    }
    unsigned char *current = (unsigned char *)malloc(len ? len : 1);
    if (!current) {
        fprintf(stderr, "error=out_of_memory\n");
        free(expected);
        return false;
    }
    if (!read_at(path, offset, current, len)) {
        free(expected);
        free(current);
        return false;
    }
    *matches = same_bytes(current, expected, len);
    free(expected);
    free(current);
    return true;
}

