static bool parse_apply_list(const wchar_t *value, Selection *selection)
{
    wchar_t *copy = _wcsdup(value);
    if (!copy) {
        return false;
    }
    wchar_t *context = NULL;
    wchar_t *token = wcstok(copy, L",", &context);
    while (token) {
        while (*token == L' ' || *token == L'\t') {
            token++;
        }
        if (_wcsicmp(token, L"recommended") == 0) {
            selection->dgvoodoo_resolution = true;
            selection->historical = true;
            selection->retraining_drag = true;
            selection->throne = true;
            selection->ammo = true;
            selection->kawanakajima = true;
            selection->odawara = true;
        } else if (_wcsicmp(token, L"all") == 0) {
            selection->dgvoodoo_resolution = true;
            selection->historical = true;
            selection->retraining_drag = true;
            selection->throne = true;
            selection->unit = true;
            selection->harvest = true;
            selection->ammo = true;
            selection->kawanakajima = true;
            selection->odawara = true;
            selection->advisor = true;
        } else if (_wcsicmp(token, L"historical") == 0) {
            selection->historical = true;
        } else if (_wcsicmp(token, L"retraining-drag") == 0 ||
                   _wcsicmp(token, L"retraining-drag-crash") == 0) {
            selection->retraining_drag = true;
        } else if (_wcsicmp(token, L"throne") == 0 || _wcsicmp(token, L"audio") == 0) {
            selection->throne = true;
        } else if (_wcsicmp(token, L"unit") == 0 || _wcsicmp(token, L"economics") == 0) {
            selection->unit = true;
        } else if (_wcsicmp(token, L"harvest") == 0) {
            selection->harvest = true;
        } else if (_wcsicmp(token, L"ammo") == 0) {
            selection->ammo = true;
        } else if (_wcsicmp(token, L"historical-battle-ai") == 0) {
            selection->kawanakajima = true;
            selection->odawara = true;
        } else if (_wcsicmp(token, L"kawanakajima") == 0 ||
                   _wcsicmp(token, L"kawanakajima-ai") == 0) {
            selection->kawanakajima = true;
        } else if (_wcsicmp(token, L"odawara") == 0 ||
                   _wcsicmp(token, L"odawara-ai") == 0 ||
                   _wcsicmp(token, L"odawara-routing") == 0) {
            selection->odawara = true;
        } else if (_wcsicmp(token, L"advisor") == 0 ||
                   _wcsicmp(token, L"advisor-quotes") == 0 ||
                   _wcsicmp(token, L"random-advisor") == 0) {
            selection->advisor = true;
        } else if (_wcsicmp(token, L"dgvoodoo-resolution") == 0 ||
                   _wcsicmp(token, L"dgvoodoo") == 0 ||
                   _wcsicmp(token, L"resolution-slider") == 0 ||
                   _wcsicmp(token, L"video-resolution") == 0) {
            selection->dgvoodoo_resolution = true;
        } else if (*token != L'\0') {
            fwprintf(stderr, L"error=unknown_fix name=%ls\n", token);
            free(copy);
            return false;
        }
        token = wcstok(NULL, L",", &context);
    }
    free(copy);
    if (selection->advisor) selection->throne = true;
    return selection->dgvoodoo_resolution || selection->historical || selection->retraining_drag || selection->throne ||
           selection->unit || selection->harvest || selection->ammo || selection->kawanakajima || selection->odawara ||
           selection->advisor;
}

int wmain(int argc, wchar_t **argv)
{
    const wchar_t *target = NULL;
    const wchar_t *apply_value = NULL;
    const wchar_t *payload = NULL;
    const wchar_t *uninstaller = NULL;
    bool verify = false;
    bool uninstall = false, archive_conflicts = false, keep_legacy_wrappers = false;

    _setmode(_fileno(stdout), _O_BINARY);
    _setmode(_fileno(stderr), _O_BINARY);
    /* Open the log before parsing so CLI and startup failures are retained. */
    const wchar_t *log_target = NULL;
    for (int i = 1; i + 1 < argc; ++i) {
        if (_wcsicmp(argv[i], L"--target") == 0) log_target = argv[i + 1];
    }
    for (int i = 1; i + 1 < argc; ++i) {
        if (_wcsicmp(argv[i], L"--log") == 0) {
            if (!tx_log_safe(argv[i + 1], log_target)) {
                fwprintf(stderr, L"error=unsafe_log path=%ls\n", argv[i + 1]);
                return 2;
            }
            patch_log_file = _wfopen(argv[i + 1], L"ab");
            if (!patch_log_file) {
                fwprintf(stderr, L"error=log_open_failed path=%ls\n", argv[i + 1]);
                return 2;
            }
            break;
        }
    }
    fprintf(stdout, "version=1.3.2 phase=start\n");
    wchar_t helper_path[MAX_PATH_CHARS];
    char hash[65];
    if (GetModuleFileNameW(NULL, helper_path, MAX_PATH_CHARS) && file_sha256(helper_path, hash)) {
        fprintf(stdout, "helper_sha256=%s\n", hash);
    }

    for (int i = 1; i < argc; ++i) {
        if (_wcsicmp(argv[i], L"--target") == 0 && i + 1 < argc) {
            target = argv[++i];
        } else if (_wcsicmp(argv[i], L"--apply") == 0 && i + 1 < argc) {
            apply_value = argv[++i];
        } else if (_wcsicmp(argv[i], L"--verify") == 0) {
            verify = true;
        } else if (_wcsicmp(argv[i], L"--payload") == 0 && i + 1 < argc) {
            payload = argv[++i];
        } else if (_wcsicmp(argv[i], L"--uninstaller") == 0 && i + 1 < argc) {
            uninstaller = argv[++i];
        } else if (_wcsicmp(argv[i], L"--uninstall") == 0) {
            uninstall = true;
        } else if (_wcsicmp(argv[i], L"--archive-conflicts") == 0) {
            archive_conflicts = true;
        } else if (_wcsicmp(argv[i], L"--keep-legacy-wrappers") == 0) {
            keep_legacy_wrappers = true;
        } else if (_wcsicmp(argv[i], L"--log") == 0 && i + 1 < argc) {
            ++i;
        } else if (_wcsicmp(argv[i], L"--version") == 0 && argc == 2) {
            return 0;
        } else {
            fwprintf(stderr, L"error=unknown_argument arg=%ls\n", argv[i]);
            print_usage();
            return 1;
        }
    }

    if (!target || (verify && (apply_value || payload || uninstaller || uninstall || archive_conflicts || keep_legacy_wrappers)) ||
        (uninstall && (apply_value || payload || uninstaller)) || ((archive_conflicts || keep_legacy_wrappers) && !uninstall) ||
        (!verify && !uninstall && !apply_value)) {
        print_usage();
        return 1;
    }

    if (uninstall) return lifecycle_uninstall(target, archive_conflicts, keep_legacy_wrappers);
    if (uninstaller) {
        Selection lifecycle_selection = {0};
        if (!parse_apply_list(apply_value, &lifecycle_selection)) { print_usage(); return 1; }
        fwprintf(stdout, L"options=%ls payload=%ls\n", apply_value, payload ? payload : L"none");
        return lifecycle_install(target, &lifecycle_selection, payload, uninstaller);
    }

    wchar_t exe_path[MAX_PATH_CHARS];
    if (!resolve_exe_path(target, exe_path, MAX_PATH_CHARS)) {
        return 2;
    }
    fwprintf(stdout, L"target=%ls\n", exe_path);

    if (!check_file_size(exe_path)) {
        return 2;
    }
    if (file_sha256(exe_path, hash)) fprintf(stdout, "before_sha256=%s\n", hash);

    if (verify) {
        bool ok = verify_all(exe_path);
        return patch_log_failed ? 3 : (ok ? 0 : 2);
    }

    Selection selection = {0};
    if (!parse_apply_list(apply_value, &selection)) {
        print_usage();
        return 1;
    }

    fwprintf(stdout, L"options=%ls payload=%ls\n", apply_value, payload ? payload : L"none");
    bool ok = apply_transaction(exe_path, &selection, payload);
    if (file_sha256(exe_path, hash)) fprintf(stdout, "after_sha256=%s\n", hash);
    fprintf(stdout, "phase=%s result=%d\n", ok ? "complete" : "failed", ok ? 0 : 2);
    tx_finish_diagnostics();
    if (patch_log_failed) {
        fprintf(stdout, "phase=diagnostics_failed result=3 game_changes=%s\n", patch_game_outcome);
        return 3;
    }
    return ok ? 0 : 2;
}
