def test_conflict_requires_choice_then_archives_changed_file(tmp_path):
    game = fixtures.make_clean_game(tmp_path)
    original = (game / "ShogunM.exe").read_bytes()
    install(game, marker(tmp_path))
    current = bytearray((game / "ShogunM.exe").read_bytes())
    current[1024] ^= 1
    changed = bytes(current)
    (game / "ShogunM.exe").write_bytes(changed)
    before = inventory(game)
    result = invoke(game, "--uninstall")
    assert result.returncode == 4, result.stdout + result.stderr
    assert inventory(game) == before
    assert registry_key(game) is not None
    result = invoke(game, "--uninstall", "--archive-conflicts")
    assert result.returncode == 0, result.stdout + result.stderr
    assert (game / "ShogunM.exe").read_bytes() == original
    archives = list(game.glob("Unofficial Shogun Patch recovery*"))
    assert archives and any(p.read_bytes() == changed for d in archives for p in d.rglob("*") if p.is_file())


