@pytest.mark.parametrize("wrappers", ["absent", "third-party", "identical-bundle"])
def test_full_wrapper_payload_has_proven_before_state(tmp_path, wrappers):
    game = fixtures.make_clean_game(tmp_path)
    vendor = fixtures.PROJECT / "vendor" / "dgvoodoo2"
    for name in ("DDraw.dll", "D3DImm.dll", "D3D9.dll", "dgVoodoo.conf"):
        if wrappers == "third-party":
            (game / name).write_bytes(b"my original " + name.encode())
        elif wrappers == "identical-bundle":
            (game / name).write_bytes((vendor / name).read_bytes())
    before = inventory(game)
    result = invoke(game, "--apply", "all", "--payload", str(vendor), "--uninstaller", str(marker(tmp_path)))
    assert result.returncode == 0, result.stdout + result.stderr
    if wrappers == "identical-bundle":
        assert invoke(game, "--uninstall").returncode == 4
        result = invoke(game, "--uninstall", "--keep-legacy-wrappers")
        assert "warning=legacy_wrappers_retained" in result.stdout
    else:
        result = invoke(game, "--uninstall")
    assert result.returncode == 0, result.stdout + result.stderr
    assert inventory(game) == before


@pytest.mark.parametrize("backup", ["missing", "corrupt", "already-patched"])
def test_legacy_backup_recovery_preserves_unknown_evidence(tmp_path, backup):
    game = fixtures.make_clean_game(tmp_path)
    original = (game / "ShogunM.exe").read_bytes()
    assert invoke(game, "--apply", "unit,historical").returncode == 0
    path = game / fixtures.SHARED_BACKUP
    if backup == "missing":
        path.unlink()
    elif backup == "corrupt":
        path.write_bytes(b"not a game backup")
    else:
        path.write_bytes((game / "ShogunM.exe").read_bytes())
    install(game, marker(tmp_path))
    result = invoke(game, "--uninstall")
    assert result.returncode == 0, result.stdout + result.stderr
    assert (game / "ShogunM.exe").read_bytes() == original
    if backup == "corrupt":
        assert path.read_bytes() == b"not a game backup"
    else:
        assert not path.exists()


