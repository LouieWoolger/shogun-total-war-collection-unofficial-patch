pytestmark = pytest.mark.skipif(os.name != "nt", reason="Windows lifecycle")
STATE = ".unofficial-shogun-patch"
UNINSTALLER = "Uninstall Unofficial Shogun Patch.exe"


@pytest.fixture(autouse=True)
def remove_test_registration(tmp_path):
    yield
    # Negative cases intentionally retain their removal path. Remove only this
    # fixture's HKCU entries afterwards; keep the on-disk evidence intact.
    import winreg
    parent = r"Software\Microsoft\Windows\CurrentVersion\Uninstall"
    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, parent, 0,
                        winreg.KEY_READ | winreg.KEY_WOW64_32KEY) as key:
        names = [winreg.EnumKey(key, i) for i in range(winreg.QueryInfoKey(key)[0])]
        for name in names:
            if not name.startswith("UnofficialShogunPatch-"):
                continue
            with winreg.OpenKey(key, name) as child:
                try:
                    location = winreg.QueryValueEx(child, "InstallLocation")[0]
                except FileNotFoundError:
                    continue
            if os.path.commonpath([os.path.normcase(str(tmp_path)), os.path.normcase(location)]) == os.path.normcase(str(tmp_path)):
                winreg.DeleteKeyEx(winreg.HKEY_CURRENT_USER, parent + "\\" + name, winreg.KEY_WOW64_32KEY)


def invoke(game: Path, *args: str, cwd: Path | None = None):
    return subprocess.run([str(fixtures.PATCHER), "--target", str(game), *args],
                          cwd=cwd, capture_output=True, text=True, encoding="utf-8", timeout=45)


def marker(tmp_path: Path) -> Path:
    path = tmp_path / "generated-uninstaller.exe"
    path.write_bytes(b"MZ" + b"test uninstaller payload\0" * 64)
    return path


def install(game: Path, payload: Path, fixes="historical", **kwargs):
    result = invoke(game, "--apply", fixes, "--uninstaller", str(payload), **kwargs)
    assert result.returncode == 0, result.stdout + result.stderr
    return result


def inventory(game: Path):
    return {str(p.relative_to(game)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in game.rglob("*") if p.is_file()}


def registry_key(game: Path):
    import winreg
    parent = r"Software\Microsoft\Windows\CurrentVersion\Uninstall"
    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, parent, 0,
                        winreg.KEY_READ | winreg.KEY_WOW64_32KEY) as key:
        for i in range(winreg.QueryInfoKey(key)[0]):
            name = winreg.EnumKey(key, i)
            if not name.startswith("UnofficialShogunPatch-"):
                continue
            with winreg.OpenKey(key, name) as child:
                location = winreg.QueryValueEx(child, "InstallLocation")[0]
                if os.path.normcase(location) == os.path.normcase(str(game.resolve())):
                    return name, {winreg.EnumValue(child, n)[0]: winreg.EnumValue(child, n)[1]
                                  for n in range(winreg.QueryInfoKey(child)[1])}
    return None


def test_clean_install_uninstall_restores_inventory_and_registration(tmp_path):
    game = fixtures.make_clean_game(tmp_path)
    (game / "saves.dat").write_bytes(b"unrelated personal save")
    before = inventory(game)
    install(game, marker(tmp_path))
    assert (game / UNINSTALLER).is_file()
    entry = registry_key(game)
    assert entry is not None
    assert "Unofficial Shogun" in entry[1]["DisplayName"]
    assert entry[1]["UninstallString"] == f'"{game / UNINSTALLER}"'
    assert entry[1]["QuietUninstallString"] == f'"{game / UNINSTALLER}" /S'
    result = invoke(game, "--uninstall", cwd=tmp_path.parent)
    assert result.returncode == 0, result.stdout + result.stderr
    assert inventory(game) == before
    assert registry_key(game) is None


